"""Poem-to-video: each line of a short poem becomes its own clip, with the
line set on screen. One clip per line is generated by Higgsfield Kling 3 Pro
through Comfy Router (queued with models.submit), the text is burned in
locally with ffmpeg, and the finished clips are joined into one film.
"""
from __future__ import annotations

import json
import os
import subprocess
import textwrap
import threading
import time
import uuid
from pathlib import Path

import httpx
import imageio_ffmpeg
from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from PIL import Image, ImageDraw, ImageFont
from pydantic import BaseModel, Field

from comfy_sdk import Comfy, ComfyError, InsufficientCredits
from comfy_sdk.router_exceptions import ConcurrencyLimitExceeded, RateLimited, RouterError

HERE = Path(__file__).parent
ENV_PATH = HERE.parent / ".env"  # shared with the app next door
load_dotenv(ENV_PATH, override=True)  # .env wins over the shell

MODEL = "higgsfield/higgsfield-kling-3-pro"
MAX_LINES = 8
OUT = HERE / "outputs"
STORE = HERE / "poems.json"
OUT.mkdir(exist_ok=True)
FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()
FONT = "/System/Library/Fonts/Supplemental/Georgia Italic.ttf"
SIZES = {"16:9": (1280, 720), "9:16": (720, 1280), "1:1": (960, 960)}

_store_lock = threading.Lock()
_poem_locks: dict[str, threading.Lock] = {}
_client: Comfy | None = None


class CreditsError(Exception):
    pass


def client() -> Comfy:
    global _client
    if _client is None:
        if not os.environ.get("COMFY_API_KEY"):
            raise HTTPException(503, f"COMFY_API_KEY is missing. Put it in {ENV_PATH} and restart.")
        _client = Comfy()
    return _client


def load() -> dict:
    try:
        return json.loads(STORE.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def save(poem: dict) -> dict:
    with _store_lock:
        data = load()
        data[poem["id"]] = poem
        STORE.write_text(json.dumps(data, indent=2))
    return poem


def err_fields(exc: Exception) -> dict:
    return {"error_type": getattr(exc, "error_type", None) or getattr(exc, "code", None) or "error",
            "error": getattr(exc, "detail", None) or str(exc)}


# --- text overlay -------------------------------------------------------------
def caption_png(text: str, size: tuple[int, int], path: Path) -> None:
    w, h = size
    img = Image.new("RGBA", size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    fs = max(28, int(min(w, h) * 0.055))
    try:
        font = ImageFont.truetype(FONT, fs)
    except OSError:
        font = ImageFont.load_default(size=fs)
    chars = max(14, int(w / (fs * 0.5)))
    wrapped = "\n".join(textwrap.wrap(text, width=chars)) or text
    box = draw.multiline_textbbox((0, 0), wrapped, font=font, align="center", spacing=fs // 3)
    tw, th = box[2] - box[0], box[3] - box[1]
    y = int(h * 0.86) - th
    # soft scrim behind the text for legibility on any footage
    scrim = Image.new("RGBA", size, (0, 0, 0, 0))
    ImageDraw.Draw(scrim).rectangle([0, y - fs, w, h], fill=(0, 0, 0, 110))
    img = Image.alpha_composite(scrim, img)
    draw = ImageDraw.Draw(img)
    draw.multiline_text(((w - tw) / 2, y), wrapped, font=font, fill=(255, 255, 255, 255),
                        align="center", spacing=fs // 3, stroke_width=max(1, fs // 18),
                        stroke_fill=(0, 0, 0, 200))
    img.save(path)


def burn_in(src: Path, png: Path, dst: Path, size: tuple[int, int], fps: int = 24) -> None:
    w, h = size
    vf = (f"[0:v]scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},"
          f"fps={fps},setsar=1[v];[v][1:v]overlay=0:0,format=yuv420p")
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-i", str(src), "-i", str(png),
                    "-filter_complex", vf, "-an", "-c:v", "libx264", "-preset", "veryfast",
                    "-crf", "20", str(dst)], check=True)


def concat(clips: list[Path], dst: Path) -> None:
    listing = dst.with_suffix(".txt")
    listing.write_text("".join(f"file '{c.name}'\n" for c in clips))
    subprocess.run([FFMPEG, "-y", "-loglevel", "error", "-f", "concat", "-safe", "0",
                    "-i", str(listing), "-c", "copy", str(dst)], check=True, cwd=dst.parent)
    listing.unlink()


# --- per-clip state machine -----------------------------------------------------
def build_prompt(line: str, style: str) -> str:
    return (f"A cinematic shot visualizing this line of poetry: \"{line}\". "
            f"{style.strip() + '. ' if style.strip() else ''}"
            "Evocative, atmospheric, no text, letters or captions in frame.")


def try_submit(poem: dict, clip: dict) -> None:
    body = {"prompt": build_prompt(clip["line"], poem["style"]),
            "aspect_ratio": poem["aspect_ratio"], "duration": poem["duration"],
            "sound": "off", "cfg_scale": 0.5}
    try:
        h = client().models.submit(MODEL, body)
    except InsufficientCredits:
        raise CreditsError()
    except (ConcurrencyLimitExceeded, RateLimited):
        clip["state"] = "WAITING"  # resubmit on the next poll
        return
    except (RouterError, ComfyError) as exc:
        clip.update(state="FAILED", **err_fields(exc))
        return
    clip.update(state="IN_QUEUE", request_id=h.request_id, model=h.model)


def advance(poem: dict, idx: int, clip: dict) -> None:
    if clip["state"] in ("DONE", "FAILED"):
        return
    if clip["state"] == "WAITING":
        try_submit(poem, clip)
        return
    handle = client().models.handle(clip["model"], clip["request_id"])
    try:
        upd = handle.status()
    except InsufficientCredits:
        raise CreditsError()
    except (RouterError, ComfyError) as exc:
        clip.update(state="FAILED", **err_fields(exc))
        return
    clip["queue_position"] = upd.queue_position
    if not upd.is_completed:
        clip["state"] = upd.status or clip["state"]
        return
    if upd.error_type:  # COMPLETED but failed / cancelled
        clip.update(state="FAILED", error_type=upd.error_type,
                    error=str(upd.raw.get("detail") or upd.raw.get("error") or ""))
        return
    try:
        result = handle.get(timeout=120)
    except (RouterError, ComfyError) as exc:
        clip.update(state="FAILED", **err_fields(exc))
        return
    pstatus = result.get("status") if isinstance(result, dict) else None
    url = (result.get("video") or {}).get("url") if isinstance(result, dict) else None
    if pstatus in ("nsfw", "failed", "canceled") or not url:
        clip.update(state="FAILED", error_type=pstatus or "no_output",
                    error=(result.get("error") if isinstance(result, dict) else None)
                    or "The model finished without a video.")
        return
    # download promptly (24h retention), then burn the line in
    base = f"{poem['id']}_{idx:02d}"
    raw, png, final = OUT / f"{base}_raw.mp4", OUT / f"{base}_text.png", OUT / f"{base}.mp4"
    with httpx.stream("GET", url, follow_redirects=True, timeout=300) as r:
        r.raise_for_status()
        with open(raw, "wb") as f:
            for chunk in r.iter_bytes():
                f.write(chunk)
    size = SIZES[poem["aspect_ratio"]]
    caption_png(clip["line"], size, png)
    burn_in(raw, png, final, size)
    png.unlink(missing_ok=True)
    clip.update(state="DONE", file=f"/outputs/{final.name}", raw_file=f"/outputs/{raw.name}")


# --- API ----------------------------------------------------------------------
class PoemIn(BaseModel):
    poem: str = Field(min_length=1, max_length=4000)
    style: str = Field("", max_length=300)
    aspect_ratio: str = Field("16:9", pattern=r"^(16:9|9:16|1:1)$")
    duration: int = Field(4, ge=3, le=8)


app = FastAPI()

CREDITS_MSG = ("Your Comfy workspace is out of credits. Add credits at platform.comfy.org, "
               "then try again.")


@app.get("/api/health")
def health():
    return {"model": MODEL, "key_present": bool(os.environ.get("COMFY_API_KEY")),
            "env_path": str(ENV_PATH), "max_lines": MAX_LINES}


@app.post("/api/poems")
def create(body: PoemIn):
    lines = [ln.strip() for ln in body.poem.splitlines() if ln.strip()]
    if not lines:
        raise HTTPException(422, "The poem has no lines.")
    if len(lines) > MAX_LINES:
        raise HTTPException(422, f"Keep it to {MAX_LINES} lines or fewer (got {len(lines)}).")
    poem = {"id": uuid.uuid4().hex[:10], "created": time.time(), "style": body.style,
            "aspect_ratio": body.aspect_ratio, "duration": body.duration,
            "clips": [{"line": ln, "state": "WAITING"} for ln in lines], "film": None}
    try:
        for clip in poem["clips"]:
            try_submit(poem, clip)
    except CreditsError:
        save(poem)  # whatever was already submitted is still tracked
        return JSONResponse({"error": "insufficient_credits", "detail": CREDITS_MSG,
                             "poem": poem}, status_code=402)
    return save(poem)


@app.get("/api/poems")
def list_poems():
    return sorted(load().values(), key=lambda p: p["created"], reverse=True)


@app.get("/api/poems/{pid}")
def poll(pid: str):
    lock = _poem_locks.setdefault(pid, threading.Lock())
    with lock:
        poem = load().get(pid)
        if not poem:
            raise HTTPException(404, "unknown poem")
        try:
            for i, clip in enumerate(poem["clips"]):
                advance(poem, i, clip)
        except CreditsError:
            save(poem)
            return JSONResponse({"error": "insufficient_credits", "detail": CREDITS_MSG,
                                 "poem": poem}, status_code=402)
        states = [c["state"] for c in poem["clips"]]
        if not poem["film"] and all(s in ("DONE", "FAILED") for s in states) and "DONE" in states:
            done = [OUT / Path(c["file"]).name for c in poem["clips"] if c["state"] == "DONE"]
            film = OUT / f"{pid}_film.mp4"
            concat(done, film)
            poem["film"] = f"/outputs/{film.name}"
        return save(poem)


@app.get("/download/{name}")
def download(name: str):
    path = (OUT / name).resolve()
    if path.parent != OUT.resolve() or not path.exists():
        raise HTTPException(404)
    return FileResponse(path, media_type="video/mp4", filename=name)


app.mount("/outputs", StaticFiles(directory=OUT), name="outputs")
app.mount("/", StaticFiles(directory=HERE / "static", html=True), name="static")
